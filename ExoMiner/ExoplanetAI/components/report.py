"""
report.py - Scientific Exoplanet Candidate Analysis Report Generator.
Generates a downloadable, professional laboratory vetting report.
"""

from typing import Dict, Any, Optional
import datetime


def generate_candidate_report(
    target_id: str,
    prediction_result: Dict[str, Any],
    dataset_name: str = "Photometric Light Curve",
    rows_count: Optional[int] = None
) -> str:
    """
    Generates a high-precision markdown/text scientific analysis report.
    """
    now_utc = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    features = prediction_result.get("features_used", {})
    is_exo = prediction_result.get("is_exoplanet", False)
    pred_str = prediction_result.get("prediction")
    if pred_str:
        verdict_str = pred_str.upper()
    elif is_exo:
        verdict_str = "TRANSIT DETECTED — CANDIDATE FOR FURTHER ANALYSIS"
    else:
        verdict_str = "NO TRANSIT DETECTED — INCONCLUSIVE"

    conf = prediction_result.get("confidence")
    if conf is not None and conf > 0.0 and verdict_str != "NO TRANSIT DETECTED — INCONCLUSIVE" and "UNABLE TO EVALUATE" not in verdict_str:
        conf_str = f"{conf * 100.0:.2f}%"
    else:
        conf_str = "N/A (Inconclusive)"
    grade = prediction_result.get("confidence_grade", "Inconclusive")
    model_type = prediction_result.get("model_type", "Random Forest Ensemble")
    is_heuristic = prediction_result.get("is_heuristic", False)
    mode_str = "UNCALIBRATED ASTROPHYSICAL HEURISTIC (MODEL INFERENCE BYPASS)" if is_heuristic else "MACHINE LEARNING INFERENCE"

    report = f"""================================================================================
EXOPLANET AI • ASTRONOMICAL SIGNAL ANALYSIS VETTING REPORT
NASA Kepler & TESS Photometry Pipeline • Version 2.2.0
================================================================================

1. OBSERVATION METADATA
--------------------------------------------------------------------------------
Target Designation   : {target_id}
Dataset Origin       : {dataset_name}
Cadence Records      : {rows_count if rows_count else 'Standard Observation Window'}
Timestamp (UTC)      : {now_utc}
Classifier Engine    : {model_type}
Execution Mode       : {mode_str}

2. CLASSIFICATION DIAGNOSTIC SUMMARY
--------------------------------------------------------------------------------
VETTING VERDICT      : {verdict_str}
MODEL SCORE          : {conf_str}
CONFIDENCE GRADE     : {grade}
EXOPLANET PROBABILITY: {prediction_result.get('probability_exoplanet', 0.0) * 100:.2f}%
FALSE ALARM RISK     : {prediction_result.get('probability_non_exoplanet', 0.0) * 100:.2f}%

3. ASTROPHYSICAL FEATURE READOUTS
--------------------------------------------------------------------------------
Transit Depth (ΔF/F) : {float(features.get('transit_depth') or 0.0):.6f} ({float(features.get('transit_depth') or 0.0)*100:.3f}% / {float(features.get('transit_depth') or 0.0)*1e6:.0f} ppm)
Orbital Period       : {f"{features['period_days']:.4f} days" if features.get('period_days') is not None else "Undetermined (Non-periodic / Noise)"}
Transit Duration     : {f"{features['duration_hours']:.2f} hours" if features.get('duration_hours') is not None else "Undetermined"}
Signal-to-Noise (SNR): {float(features.get('snr') or 0.0):.2f}
Photometric Noise (σ): {float(features.get('flux_std') or 0.0):.6f}
Flux Skewness        : {float(features.get('flux_skew') or 0.0):.4f}
Flux Kurtosis        : {float(features.get('flux_kurtosis') or 0.0):.4f}

4. SCIENTIFIC ASSESSMENT NARRATIVE
--------------------------------------------------------------------------------
{prediction_result.get('vetting_summary', 'Automated photometric transit signal extraction completed.')}

5. ASTROPHYSICAL DISCLAIMER & CITATION
--------------------------------------------------------------------------------
NOTICE: This report was generated by an educational and research prototype.
Predictions represent AI-assisted statistical candidates and do NOT constitute
definitive scientific confirmation of an exoplanet. Ground-truth confirmation
requires high-resolution radial velocity Doppler spectroscopy and independent
multi-epoch transit timing analysis.

Data Sources & References:
- NASA Exoplanet Archive (Caltech/IPAC)
- Mikulski Archive for Space Telescopes (STScI)
- Lightkurve Collaboration (AAS 2018)

================================================================================
END OF REPORT • GENERATED BY EXOPLANET AI
================================================================================
"""
    return report
